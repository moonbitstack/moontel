"""Generate the GenAI semantic-convention constants in `src/semconv/`.

The names come from the registry of the OpenTelemetry GenAI semantic conventions
and nowhere else: an attribute key invented here would be a key no backend,
dashboard or collector knows, which is worse than a missing constant.

    python3 scripts/gen_semconv.py                     # fetch the pinned commit
    python3 scripts/gen_semconv.py --source DIR        # read a local checkout
    python3 scripts/gen_semconv.py --check             # fail if the output differs

The commit is pinned below. Moving the pin is a deliberate commit of its own, so a
new upstream release never changes this library's constants as a side effect of a
build.

Only the Python standard library is used. The YAML is read by the small scanner
below rather than by a YAML library, because the registry is machine-written and
has one shape: a top-level section, then blocks of `- name: value` items whose own
scalars sit two spaces deeper.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys
import urllib.request

COMMIT = "aa3b7f4394245fec260013898049780975a407a4"
BASE = (
    "https://raw.githubusercontent.com/open-telemetry/semantic-conventions-genai/"
    f"{COMMIT}/model/gen-ai/"
)

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "semconv"

HEADER = """\
// Copyright 2026 Leo Cheng
// SPDX-License-Identifier: Apache-2.0
//
// Generated by `scripts/gen_semconv.py` from the OpenTelemetry GenAI semantic
// conventions at commit {commit}. Do not edit: move the pin and regenerate.
"""

IDENT = re.compile(r"[^0-9A-Za-z]+")
FOLDED = {">", "|", ">-", "|-", ""}


def ident(name: str) -> str:
    """A MoonBit identifier for a dotted name, e.g. `gen_ai.request.model`."""
    return IDENT.sub("_", name).strip("_").lower()


def unquote(text: str) -> str:
    text = text.strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "'\"":
        return text[1:-1]
    return text


def blocks(text: str, section: str) -> list[dict[str, str]]:
    """The items of one top-level section, each a mapping of its own scalars."""
    found: list[dict[str, str]] = []
    in_section = False
    current: dict[str, str] | None = None
    for raw in text.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        indent = len(raw) - len(raw.lstrip())
        if indent == 0:
            in_section = raw.rstrip().startswith(section + ":")
            current = None
            continue
        if not in_section:
            continue
        stripped = raw.lstrip()
        if indent == 2 and stripped.startswith("- "):
            current = {}
            found.append(current)
            key, _, value = stripped[2:].partition(":")
            current[key.strip()] = unquote(value)
            continue
        if current is None or indent != 4:
            continue
        key, sep, value = stripped.partition(":")
        if sep and value.strip():
            current.setdefault(key.strip(), unquote(value))
    return found


def fetch(name: str, source: pathlib.Path | None) -> str:
    if source is not None:
        return (source / name).read_text(encoding="utf-8")
    with urllib.request.urlopen(BASE + name) as response:
        return response.read().decode("utf-8")


def wrap(text: str, width: int) -> list[str]:
    lines: list[str] = []
    line = ""
    for word in text.split():
        if line and len(line) + 1 + len(word) > width:
            lines.append(line)
            line = word
        else:
            line = word if not line else line + " " + word
    if line:
        lines.append(line)
    return lines


def brief(block: dict[str, str]) -> str:
    """The one-line summary of an item, empty when upstream wrote none."""
    text = " ".join(block.get("brief", "").split())
    if text in FOLDED or not text:
        return ""
    if text.endswith("."):
        text = text[:-1]
    if len(text) > 120:
        text = text[:117].rstrip() + "..."
    return text


def collect(
    blocks_: list[dict[str, str]], field: str, prefix: str
) -> list[tuple[str, str, str]]:
    seen: dict[str, str] = {}
    for block in blocks_:
        name = block.get(field, "")
        if not name:
            continue
        seen.setdefault(name, brief(block))
    return sorted((prefix + ident(name), name, text) for name, text in seen.items())


def render(intro: str, entries: list[tuple[str, str, str]]) -> str:
    body = [HEADER.format(commit=COMMIT).rstrip(), "", "///|"]
    for line in intro.splitlines():
        body.append(f"/// {line}".rstrip())
    for name, value, text in entries:
        body.append("")
        body.append("///|")
        line = f"`{value}`" + (f": {text}" if text else ".")
        for piece in wrap(line, 84):
            body.append(f"/// {piece}".rstrip())
        body.append(f'pub let {name} : String = "{value}"')
    body.append("")
    return "\n".join(body)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=pathlib.Path, default=None)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    attributes = collect(blocks(fetch("registry.yaml", args.source), "attributes"), "key", "")
    metrics = collect(
        blocks(fetch("metrics.yaml", args.source), "metrics")
        + blocks(fetch("token-metrics.yaml", args.source), "metrics"),
        "name",
        "",
    )
    spans = collect(blocks(fetch("spans.yaml", args.source), "spans"), "type", "")
    events = collect(blocks(fetch("events.yaml", args.source), "events"), "name", "")

    files = {
        OUT / "genai.g.mbt": render(
            "Attribute keys the GenAI semantic conventions define.\n\n"
            "A key is what a span, a metric point or a log record writes, and the\n"
            "spelling is what a backend matches on: a near miss is a value no\n"
            "dashboard shows.",
            attributes,
        ),
        OUT / "genai_metric.g.mbt": render(
            "Metric names the GenAI semantic conventions define. The unit and the\n"
            "instrument of each one are stated at its definition upstream.",
            metrics,
        ),
        OUT / "genai_signal.g.mbt": render(
            "Span types and event names the GenAI semantic conventions define.\n\n"
            "A span's type is the operation it covers, which its name repeats\n"
            "followed by the model; an event is a point in time inside a span.",
            spans + events,
        ),
    }

    OUT.mkdir(parents=True, exist_ok=True)
    changed = False
    for path, text in files.items():
        wanted = text.encode("utf-8").replace(b"\r\n", b"\n")
        if path.exists() and path.read_bytes() == wanted:
            continue
        if args.check:
            print(f"{path.relative_to(ROOT)} is out of date", file=sys.stderr)
            return 1
        path.write_bytes(wanted)
        changed = True
    print(
        f"{len(attributes)} attribute keys, {len(metrics)} metrics, "
        f"{len(spans)} span types, {len(events)} events"
        + ("" if changed else " (unchanged)")
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
