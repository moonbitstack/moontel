"""Write the module version into a file the sheet can read.

`moon.mod` is the one place the version is written; every page reads it from
`version.js` rather than repeating it, so a release cannot leave a stale number on the
site. The file is generated, committed, and checked in CI the same way the reference
is.

    python3 scripts/gen_version.py
    git diff --exit-code docs/version.js
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "version.js"


def main() -> int:
    manifest = (ROOT / "moon.mod").read_text(encoding="utf-8")
    found = re.search(r'^version\s*=\s*"([^"]+)"', manifest, re.MULTILINE)
    if not found:
        sys.stderr.write("moon.mod has no version\n")
        return 1
    version = found.group(1)

    TARGET.write_text(
        "// Copyright 2026 Leo Cheng\n"
        "// SPDX-License-Identifier: Apache-2.0\n"
        "\n"
        "// Generated by `scripts/gen_version.py` from `moon.mod`; do not edit by hand.\n"
        f'globalThis.MOONTEL_VERSION = "{version}";\n',
        encoding="utf-8",
        newline="\n",
    )
    sys.stdout.write(f"wrote {TARGET.relative_to(ROOT)} ({version})\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
