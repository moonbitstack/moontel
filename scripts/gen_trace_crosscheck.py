"""Turn the recorded reference run into the MoonBit constant the replay reads.

`scripts/trace_crosscheck_expected.json` is what the OpenTelemetry Python SDK
produced for one fixed scenario; `src/crosscheck_expected_wbtest.mbt` is that same
JSON as a MoonBit string, so the replay test reads it without touching the file
system (which a wasm or js test cannot do).

    python3 scripts/gen_trace_crosscheck.py
    git diff --exit-code src/crosscheck_expected_wbtest.mbt

Both the JSON and the generated file are checked in, and CI re-runs this script
and fails on a difference: the replay is regenerated whenever the record changes,
and the record is never edited by hand.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "scripts" / "trace_crosscheck_expected.json"
TARGET = ROOT / "src" / "crosscheck_expected_wbtest.mbt"

HEADER = """// Copyright 2026 Leo Cheng
// SPDX-License-Identifier: Apache-2.0

// Generated by `scripts/gen_trace_crosscheck.py` from
// `scripts/trace_crosscheck_expected.json`; do not edit by hand. The JSON is the
// record of one run of the OpenTelemetry Python SDK, and `crosscheck_wbtest.mbt`
// replays the same scenario against this library and compares the two.

///|
/// The reference run, as JSON: two spans, the headers injected after them, and the
/// sampling decisions a ratio sampler made for a set of fixed trace ids.
let expected_json : String ="""


def moonbit_literal(text: str) -> str:
    """`text` as one MoonBit string literal.

    One line rather than one literal per JSON line: `moon fmt` joins string
    concatenations whose operands fit, so a file it would rewrite is a file that
    fails the CI check that regenerates it. A single literal is a form it leaves
    alone, and nobody reads this file by hand.
    """
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def main() -> int:
    source = SOURCE.read_text(encoding="utf-8")
    # Fail here rather than in a MoonBit test if the record is not valid JSON.
    json.loads(source)
    # A fixed newline: the generated file is compared byte for byte in CI, and a
    # Windows checkout that wrote CRLF here would fail the comparison there alone.
    TARGET.write_text(
        HEADER + " " + moonbit_literal(source) + "\n", encoding="utf-8", newline="\n"
    )
    sys.stdout.write(f"wrote {TARGET.relative_to(ROOT)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
